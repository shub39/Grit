val changelogDataPath = "com/shub39/grit/logic/generated/ChangelogData.kt"

/**
 * Extracts the changelog from CHANGELOG.md and emits it as a Kotlin constant, so the shared module
 * does not need compose-resources (and therefore Compose) to read it on any platform.
 */
val generateChangelog =
    tasks.register("generateChangelog") {
        description = "Extract changelogs from CHANGELOG.md into a generated Kotlin constant"
        val inputFile = rootProject.file("CHANGELOG.md")
        val outputDir = layout.buildDirectory.dir("generated/gritChangelog/kotlin")
        val outputFile = outputDir.map { it.file(changelogDataPath) }

        inputs.file(inputFile)
        outputs.dir(outputDir)

        doLast {
            val lines = inputFile.readLines()

            val map = mutableMapOf<String, MutableList<String>>()
            var currentVersion: String? = null

            for (line in lines) {
                when {
                    line.startsWith("## ") -> {
                        currentVersion = line.removePrefix("## ").trim()
                        map[currentVersion] = mutableListOf()
                    }

                    line.startsWith("- ") && currentVersion != null -> {
                        map[currentVersion]?.add(line.removePrefix("- ").trim())
                    }
                }
            }

            val json = buildString {
                append("[\n")

                val limitedEntries = map.entries.take(10)
                limitedEntries.forEachIndexed { index, entry ->
                    append("  {\n")
                    append("    \"version\": \"${entry.key}\",\n")
                    append("    \"changes\": [\n")

                    entry.value.forEachIndexed { i, item ->
                        append("      \"${item.replace("\"", "\\\"")}\"")
                        if (i != entry.value.lastIndex) append(",")
                        append("\n")
                    }

                    append("    ]\n")
                    append("  }")

                    if (index != limitedEntries.lastIndex) append(",")
                    append("\n")
                }

                append("]")
            }

            val literal =
                json
                    .replace("\\", "\\\\")
                    .replace("\"", "\\\"")
                    .replace("$", "\\$")
                    .replace("\r", "")
                    .replace("\n", "\\n")

            val file = outputFile.get().asFile
            file.parentFile.mkdirs()
            file.writeText(
                buildString {
                    appendLine(
                        "// Generated by the \":shared:logic:generateChangelog\" Gradle task."
                    )
                    appendLine("// Do not edit, changes are overwritten on every build.")
                    appendLine("package com.shub39.grit.logic.generated")
                    appendLine()
                    appendLine("internal object ChangelogData {")
                    appendLine("    const val JSON: String = \"$literal\"")
                    appendLine("}")
                }
            )
        }
    }

